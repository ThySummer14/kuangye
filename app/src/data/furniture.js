export function vintageStock(date, seed = "kuangye-s1") {
  let hash = 2166136261;
  for (const c of seed + date)
    hash = Math.imul(hash ^ c.charCodeAt(0), 16777619) >>> 0;
  return FURNITURE.filter((f) => f.stall === "vintage")
    .map((f, i) => ({
      ...f,
      price: Math.round(f.price * 0.7),
      order: (hash ^ (i * 2654435761)) >>> 0,
    }))
    .sort((a, b) => a.order - b.order);
}
