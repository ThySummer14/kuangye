async (page) => {
  const errors = [], results = [];
  page.on('pageerror', e => errors.push(e.message));
  for (const width of [1280, 375]) {
    await page.setViewportSize({width, height: width === 375 ? 812 : 900});
    await page.goto('http://127.0.0.1:5184/?qa#map');
    await page.waitForFunction(() => window.__KUANGYE__);
    await page.evaluate(() => window.__KUANGYE__.reset('map-navigation', 'empty'));
    await page.locator('[data-place="tasks"]').click();
    await page.waitForURL('**#tasks');
    await page.getByText('还没想好？从一个生活方向找起', {exact:true}).click();
    await page.locator('.quest-trails').scrollIntoViewIfNeeded();
    await page.screenshot({path:`output/playwright/fieldguide-discovery-${width}.png`});
    await page.getByRole('button', {name:'把生活理顺 照顾一顿饭，也照顾自己。'}).click();
    if (await page.locator('.quest-card').count() !== 4) throw Error('生活方向未呈现四件任务');
    await page.getByRole('button', {name:'学会第一道菜：番茄炒蛋：看看怎么开始', exact:true}).click();
    await page.getByRole('dialog').waitFor();
    await page.screenshot({path:`output/playwright/fieldguide-detail-${width}.png`});
    await page.getByRole('button', {name:'接下这件事', exact:true}).click();
    await page.waitForFunction(() => document.activeElement?.dataset?.activeTask === 'cook-s1');
    const card = page.locator('[data-active-task="cook-s1"]');
    if (!(await card.innerText()).includes('选一份步骤清楚的番茄炒蛋食谱')) throw Error('第一步丢失');
    await card.getByRole('button', {name:'打开出发手册 ↗'}).click();
    if (await page.getByRole('button', {name:'接下这件事', exact:true}).count()) throw Error('进行中仍可重复接取');
    await page.keyboard.press('Escape');
    await card.getByRole('button', {name:'我完成了', exact:true}).click();
    if (!(await page.locator('.review-prompt').innerText()).includes('下次再做')) throw Error('回顾未关联任务');
    await page.locator('#quest-review').fill('第一次自己做好了晚饭，下次少放一点盐。');
    await page.screenshot({path:`output/playwright/fieldguide-review-${width}.png`});
    await page.getByRole('button', {name:'完成，收下这束光', exact:true}).click();
    await page.getByRole('button', {name:'收好了，回到地图', exact:true}).click();
    await page.waitForURL('**#map');
    await page.reload();
    await page.waitForFunction(() => window.__KUANGYE__?.snapshot().completedTasks === 1);
    const saved = await page.evaluate(() => window.__KUANGYE__.snapshot());
    if (saved.home.lumens !== 5 || saved.viewport.overflow) throw Error('结算或布局异常');
    await page.locator('[data-place="tasks"]').click();
    await page.waitForURL('**#tasks');
    await page.getByRole('button', {name:'把生活理顺 照顾一顿饭，也照顾自己。'}).click();
    if (await page.locator('.quest-card').count() !== 3) throw Error('已完成任务重复推荐');
    await page.getByRole('textbox', {name:'搜索任务'}).fill('连续跑完 5 公里不停歇');
    await page.getByRole('button', {name:'连续跑完 5 公里不停歇：看看怎么开始'}).click();
    if (!await page.getByRole('button', {name:'接下这件事', exact:true}).isDisabled()) throw Error('手册绕过成长线资格');
    await page.keyboard.press('Escape');
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    if (overflow) throw Error('横向溢出');
    results.push({width, status:'PASS', completed: saved.completedTasks, lumens: saved.home.lumens});
  }
  if (errors.length) throw Error(errors.join('\n'));
  return {results, errors};
}
